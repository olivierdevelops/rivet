//! Syntax highlighting from real parser spans (PROP-2026-0002 R17, UC-08).
//!
//! ```text
//!  SourceFile ──parser.parse──▶ SyntaxTree (statement nodes + capture spans)
//!      │                              │
//!      │        per node: leading keyword (func) · captures (id, var, name, value, cond, rest…)
//!      │                  · glue literals between captures (`in`, `after`, `=`, `map`)
//!      │                              ▼
//!      │                   lex each span ─▶ classify with editors/keywords.json
//!      │                   (the table generated from src/infra/rivet.capy)
//!      ▼
//!  gap scan (text no node covers): `#` comments, the `else` section keyword and
//!  the `end` of a flat option line's sub-block (Capy keeps no node for it)
//!      ▼
//!  syntax error? ──yes──▶ keep the tokens that start before the earliest diagnostic
//!      ▼                  + that diagnostic (syntax.*, exit 2)
//!  [HighlightToken{line, col, len, class, text}]   one line each, sorted, non-overlapping
//! ```
//!
//! Classes: keyword, option, type, effect, string, interpolation, number,
//! comment, operation_id, global, variable, operator. Brackets, commas, colons,
//! object keys and whitespace are not tokens (renderers copy them unchanged).

use crate::domain::highlight::HighlightToken;
